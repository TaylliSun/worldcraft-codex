function assertBatchShape() {
  const checks = [
    [figureRows.length, 110, "人物"],
    [systemRows.length, 18, "系统"],
    [sourceRows.length, 25, "原典与史料"],
    [eventRows.length, 44, "时间事件"]
  ];
  for (const [actual, expected, label] of checks) {
    if (actual !== expected) throw new Error(`${BATCH_LABEL}${label}数量应为 ${expected}，实际为 ${actual}`);
  }
}

function buildBuddhismPantheonBatch(now = new Date().toISOString(), worldId = WORLD_ID) {
  assertBatchShape();
  const figures = figureRows.map((row, index) => buildFigureEntity(row, index, worldId, now));
  const systems = systemRows.map((row, index) => buildSystemEntity(row, figures.length + index, worldId, now));
  const sources = sourceRows.map((row, index) => buildSourceEntity(row, figures.length + systems.length + index, worldId, now));
  const relationRows = [
    ...figureSourceRelations,
    ...systemSourceRelations,
    ...membershipRelations,
    ...anchorRelations,
    ...explicitMembershipRelations,
    ...sequenceRelations,
    ...fiveWisdomKingSequence,
    ...systemCrossRelations
  ];
  return {
    key: BATCH_KEY,
    label: BATCH_LABEL,
    entities: [...figures, ...systems, ...sources],
    figures,
    systems,
    sources,
    relations: relationRows.map((row) => buildRelation(row, worldId, now)),
    timelineEvents: eventRows.map((row) => buildTimelineEvent(row, worldId, now)),
    featuredEntityIds: [
      pantheonEntityId("past-seven-buddhas", worldId),
      pantheonEntityId("seven-medicine-buddhas-system", worldId),
      pantheonEntityId("twelve-yaksha-generals", worldId),
      pantheonEntityId("eight-great-bodhisattvas", worldId),
      pantheonEntityId("wisdom-kings-system", worldId),
      pantheonEntityId("ten-rakshasi-women", worldId),
      pantheonEntityId("eight-lotus-naga-kings", worldId),
      pantheonEntityId("ten-great-disciples", worldId)
    ]
  };
}

