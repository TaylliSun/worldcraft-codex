function assertBatchShape() {
  const checks = [
    [figureRows.length, 8, "人物"],
    [conceptRows.length, 16, "概念与制度"],
    [coreSourceRows.length, 20, "核心经论"],
    [sectionRows.length, 32, "金刚经分段"],
    [sourceRows.length, 52, "全部原典与注疏"],
    [sectionRelationRows.length, 95, "分段关系"],
    [translatorRows.length, 19, "译者与注家关系"],
    [eventRows.length, 29, "时间事件"]
  ];
  for (const [actual, expected, label] of checks) {
    if (actual !== expected) throw new Error(`${BATCH_LABEL}${label}数量应为 ${expected}，实际为 ${actual}`);
  }
}

function buildBuddhismPrajnaBatch(now = new Date().toISOString(), worldId = WORLD_ID) {
  assertBatchShape();
  const figures = figureRows.map((row, index) => buildFigureEntity(row, index, worldId, now));
  const concepts = conceptRows.map((row, index) => buildConceptEntity(row, figures.length + index, worldId, now));
  const sources = sourceRows.map((row, index) => buildSourceEntity(row, figures.length + concepts.length + index, worldId, now));
  const sourceRelations = [
    ...figureRows.map((row) => buildSourceRelation(row, "figure", worldId, now)),
    ...conceptRows.map((row) => buildSourceRelation(row, "concept", worldId, now))
  ];
  return {
    key: BATCH_KEY,
    label: BATCH_LABEL,
    entities: [...figures, ...concepts, ...sources],
    figures,
    concepts,
    sources,
    coreSources: coreSourceRows.map((row) => prajnaSourceId(row.key, worldId)),
    sectionSources: sectionRows.map((row) => prajnaSourceId(row.key, worldId)),
    relations: [...sourceRelations, ...semanticRelationRows.map((row) => buildRelation(row, worldId, now))],
    timelineEvents: eventRows.map((row) => buildTimelineEvent(row, worldId, now)),
    featuredEntityIds: [
      prajnaSourceId("diamond-kumarajiva", worldId),
      prajnaSourceId("heart-xuanzang", worldId),
      prajnaSourceId("mahaprajna-600", worldId),
      prajnaEntityId("subhuti", worldId),
      prajnaEntityId("prajna-corpus", worldId),
      prajnaEntityId("prajnaparamita", worldId),
      prajnaEntityId("non-abiding", worldId),
      prajnaEntityId("thirty-two-sections", worldId)
    ]
  };
}

