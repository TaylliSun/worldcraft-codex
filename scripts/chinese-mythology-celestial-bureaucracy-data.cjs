function resolveRef(reference, worldId) {
  const [scope, key] = reference.split(":");
  if (scope === "c") return celestialEntityId(key, worldId);
  if (scope === "cs") return celestialSourceId(key, worldId);
  if (scope === "d") return daoismEntityId(key, worldId);
  if (scope === "n") return natureEntityId(key, worldId);
  if (scope === "a") return ancientEntityId(key, worldId);
  if (scope === "t") return civilizationEntityId(key, worldId);
  throw new Error(`未知星辰官署批次引用：${reference}`);
}

function buildRelation(row, worldId, now) {
  const [key, sourceRef, targetRef, kind, label, direction, strength, evidenceType, sourceCitation, historicalScope, confidence, notes] = row;
  return {
    id: `relation:${worldId}:mythology:daoism-celestial:${key}`,
    worldId,
    sourceEntityId: resolveRef(sourceRef, worldId),
    targetEntityId: resolveRef(targetRef, worldId),
    kind,
    label,
    direction,
    strength,
    evidenceType,
    sourceCitation,
    historicalScope,
    confidence,
    notes,
    updatedAt: now
  };
}

function sourceEvidenceType(row) {
  if (row.sourceEvidenceType) return row.sourceEvidenceType;
  if (/songshi|mingshi/.test(row.sourceRef)) return "historical-record";
  if (/daofa-huiyuan/.test(row.sourceRef) && row.category === "daoism-offices") return "ritual-record";
  return "primary-text";
}

function buildSourceRelation(row, kind, worldId, now) {
  return buildRelation(rel(
    `source-${kind}-${row.key}`,
    `c:${row.key}`,
    row.sourceRef,
    "主要原典入口",
    sourceEvidenceType(row),
    row.sourceCitation,
    row.historicalLayer || row.historicalPeriod || row.formationPeriod || "古籍文献层",
    "certain",
    "本边指向本条目优先核对的篇卷；异文、后世解释和地方材料仍按正文原典坐标分别阅读。",
    "custom",
    "directed",
    5
  ), worldId, now);
}

