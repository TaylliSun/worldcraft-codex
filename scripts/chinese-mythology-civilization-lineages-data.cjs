function resolveRef(reference, worldId) {
  const [scope, key] = reference.split(":");
  if (scope === "t") return civilizationEntityId(key, worldId);
  if (scope === "ts") return civilizationSourceId(key, worldId);
  if (scope === "a") return ancientEntityId(key, worldId);
  if (scope === "as") return ancientSourceId(key, worldId);
  if (scope === "n") return natureEntityId(key, worldId);
  if (scope === "ns") return natureSourceId(key, worldId);
  if (scope === "s") return ancientSourceId(key, worldId);
  throw new Error(`未知神话引用：${reference}`);
}

function buildRelation(row, worldId, now) {
  const [key, sourceRef, targetRef, kind, label, direction, strength, evidenceType, sourceCitation, historicalScope, confidence, notes] = row;
  return {
    id: `relation:${worldId}:mythology:civilization-lineages:${key}`,
    worldId,
    sourceEntityId: resolveRef(sourceRef, worldId),
    targetEntityId: resolveRef(targetRef, worldId),
    kind,
    label,
    direction,
    strength,
    evidenceType,
    sourceCitation,
    historicalScope,
    confidence,
    notes,
    updatedAt: now
  };
}

function buildSourceRelation(row, kind, worldId, now) {
  return buildRelation([
    `source-${kind}-${row.key}`,
    `t:${row.key}`,
    row.sourceRef,
    "custom",
    "原典载录",
    "directed",
    5,
    "primary-text",
    row.sourceCitation,
    row.historicalLayer || row.historicalPeriod || "古籍文献层",
    "certain",
    "指向本条目的主要原典入口；具体篇卷与版本差异见正文原典坐标。"
  ], worldId, now);
}

function buildTimelineEvent(row, worldId, now) {
  const [key, trackKey, title, summary, displayDate, era, sortOrder, primaryRef, referenceRefs, datePrecision, startValue, endValue] = row;
  return {
    id: `timeline-event:${worldId}:mythology:civilization-lineages:${key}`,
    worldId,
    entityId: resolveRef(primaryRef, worldId),
    questId: "",
    sceneId: "",
    references: referenceRefs.map((reference) => ({ kind: "entity", id: resolveRef(reference, worldId) })),
    trackId: trackId(trackKey, worldId),
    title,
    summary,
    displayDate,
    datePrecision,
    sortOrder,
    startValue,
    endValue,
    era,
    dependencyIds: [],
    updatedAt: now
  };
}

function buildCivilizationLineagesBatch(now = new Date().toISOString(), worldId = WORLD_ID) {
  const figures = figureRows.map((row, index) => buildFigureEntity(row, index, worldId, now));
  const locations = locationRows.map((row, index) => buildLocationEntity(row, figures.length + index, worldId, now));
  const sources = sourceRows.map((row, index) => buildSourceEntity(row, figures.length + locations.length + index, worldId, now));
  const sourceRelations = [
    ...figureRows.map((row) => buildSourceRelation(row, "figure", worldId, now)),
    ...locationRows.map((row) => buildSourceRelation(row, "location", worldId, now))
  ];
  return {
    key: BATCH_KEY,
    label: BATCH_LABEL,
    entities: [...figures, ...locations, ...sources],
    figures,
    locations,
    sources,
    relations: [
      ...sourceRelations,
      ...semanticRelationRows.map((row) => buildRelation(row, worldId, now))
    ],
    timelineEvents: eventRows.map((row) => buildTimelineEvent(row, worldId, now)),
    featuredEntityIds: [
      "leizu", "gaoyao", "boyi", "houji", "xie-shang", "qi-xia", "linglun", "cangjie"
    ].map((key) => civilizationEntityId(key, worldId))
  };
}

