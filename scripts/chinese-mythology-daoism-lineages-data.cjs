function normalizeHistoricalLayer(value) {
  const hasSongYuan = /五代|宋|金|元/u.test(value);
  const hasEarlier = /先秦|两汉|魏晋|六朝|隋|唐/u.test(value);
  const hasMingQing = /明|清/u.test(value);
  if (/跨时期/u.test(value) || (hasSongYuan && (hasEarlier || hasMingQing))) return "跨时期";
  if (hasMingQing) return "明清";
  if (hasSongYuan) return "宋元";
  if (/隋|唐/u.test(value)) return "隋唐";
  if (/魏晋|六朝/u.test(value)) return "魏晋六朝";
  if (/两汉/u.test(value)) return "两汉文献层";
  if (/先秦/u.test(value)) return "先秦文献层";
  return "跨时期";
}

