function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderArticle(row) {
  const headings = row.headings || ["生平与位置", "文献怎样记载", "谱系与史实边界"];
  const sections = [row.profile, row.history, row.distinction]
    .map((paragraph, index) => `<h2>${escapeHtml(headings[index])}</h2><p>${escapeHtml(paragraph)}</p>`)
    .join("");
  const sources = row.sources.map((source) => `<li>${escapeHtml(source)}</li>`).join("");
  return [
    `<p>${escapeHtml(row.lead)}</p>`,
    sections,
    "<h2>原典坐标</h2>",
    `<p>${escapeHtml(row.sourceNote)}</p>`,
    `<ul>${sources}</ul>`,
    "<h2>阅读与创作边界</h2>",
    `<p>${escapeHtml(row.boundary)}</p>`
  ].join("");
}

