function resolveRef(reference, worldId) {
  const [scope, key] = reference.split(":");
  if (scope === "l") return lineageEntityId(key, worldId);
  if (scope === "ls") return lineageSourceId(key, worldId);
  if (scope === "d") return daoismEntityId(key, worldId);
  if (scope === "ds") return daoismSourceId(key, worldId);
  if (scope === "c") return celestialEntityId(key, worldId);
  if (scope === "cs") return celestialSourceId(key, worldId);
  throw new Error(`未知道教祖师批次引用：${reference}`);
}

function buildRelation(row, worldId, now) {
  const [key, sourceRef, targetRef, kind, label, direction, strength, evidenceType, sourceCitation, historicalScope, confidence, notes] = row;
  return {
    id: `relation:${worldId}:mythology:daoism-lineages:${key}`,
    worldId,
    sourceEntityId: resolveRef(sourceRef, worldId),
    targetEntityId: resolveRef(targetRef, worldId),
    kind,
    label,
    direction,
    strength,
    evidenceType,
    sourceCitation,
    historicalScope,
    confidence,
    notes,
    updatedAt: now
  };
}

function sourceEvidenceType(row) {
  if (row.sourceEvidenceType) return row.sourceEvidenceType;
  if (/yuanshi|ganshui|hantian/.test(row.sourceRef)) return "historical-record";
  if (/daofa-huiyuan/.test(row.sourceRef)) return "ritual-record";
  return "primary-text";
}

