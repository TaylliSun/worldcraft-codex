function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderArticle(row) {
  const sections = row.sections.map(([heading, paragraphs]) => [
    `<h2>${escapeHtml(heading)}</h2>`,
    ...paragraphs.map((paragraph) => `<p>${escapeHtml(paragraph)}</p>`)
  ].join("")).join("");
  return [
    `<p>${escapeHtml(row.lead)}</p>`,
    sections,
    "<h2>原典坐标</h2>",
    `<ul>${row.sources.map((source) => `<li>${escapeHtml(source)}</li>`).join("")}</ul>`,
    "<h2>版本边界</h2>",
    `<p>${escapeHtml(row.boundary)}</p>`
  ].join("");
}

